// A paragraph. `bold` renders the whole line in semibold (used for the
// "DEALPRO IS PROVIDED AS IS." style callouts).
export interface LegalPara { p: string; bold?: boolean }

// An h4 sub-heading followed by a paragraph (e.g. "3.1 Automated Suggestions").
export interface LegalSub { sub: string; text: string }

// A bulleted list. An item may be a plain string, or a parent with a nested
// sub-list (used by Privacy §3 "With Service Providers"). When an item's text
// contains a leading "Label: rest", the renderer bolds the label.
export type LegalItem = string | { text: string; sub: string[] };
export interface LegalList { ul: LegalItem[] }

export type LegalBlock = LegalPara | LegalSub | LegalList;

export interface LegalSection {
  // Full localized heading INCLUDING its number prefix, e.g. "1. Acceptance of
  // Terms". Numbers are kept as Latin numerals across locales for consistency.
  heading: string;
  blocks: LegalBlock[];
}

export interface LegalDoc {
  intro: string;
  sections: LegalSection[];
  acceptance: string;
}

export interface LegalUi {
  termsTitle: string;
  privacyTitle: string;
  lastUpdated: string;      // includes the (locale-independent) date
  disclaimer: string;       // "English is legally binding" banner
  scrollHint: string;       // signup: prompt to scroll before accepting
  agreeTerms: string;       // signup ToS accept button
  scrollToContinue: string; // signup: button label before scrolled to bottom
  understand: string;       // in-app Privacy "I Understand"
  iAgree: string;           // in-app ToS "I Agree to Terms"
}

